  setupPasswordToggle(inputEl, buttonEl) {
    if (!inputEl || !buttonEl) return;
    buttonEl.innerHTML = this.icons.eye;
    buttonEl.setAttribute('title', 'Show password');

    buttonEl.addEventListener('click', () => {
      const isPassword = inputEl.type === 'password';
      inputEl.type = isPassword ? 'text' : 'password';
      buttonEl.innerHTML = isPassword ? this.icons.eyeOff : this.icons.eye;
      buttonEl.setAttribute('title', isPassword ? 'Hide password' : 'Show password');
    });
  }
